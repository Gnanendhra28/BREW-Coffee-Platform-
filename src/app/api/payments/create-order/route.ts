import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";
import { MENU_ITEMS } from "../../../../data/menuData";
import { checkRateLimit, getClientIp } from "../../../../lib/rateLimit";
import { maskPhone } from "../../../../lib/observability/logger";
import {
  saveStoredPaymentOrder,
  StoredPaymentOrder,
  StoredPaymentItem,
} from "../../../../lib/serverPaymentStore";

export const dynamic = "force-dynamic";

// Map MENU_ITEMS by id for fast O(1) server lookup
const MENU_MAP = new Map(MENU_ITEMS.map((item) => [item.id, item]));

const CreateOrderInputSchema = z.object({
  items: z
    .array(
      z.object({
        id: z.string().min(1, "Product ID is required"),
        quantity: z
          .number()
          .int("Quantity must be an integer")
          .min(1, "Quantity must be at least 1")
          .max(20, "Quantity cannot exceed 20 per item"),
      })
    )
    .min(1, "Order must contain at least 1 item")
    .max(30, "Order cannot exceed 30 items")
    .optional(),
  promoCode: z.string().trim().max(50).optional(),
  isMember: z.boolean().optional(),
  currency: z.string().default("INR"),
  receipt: z.string().max(100).optional(),
  customerName: z.string().max(100).optional(),
  customerPhone: z.string().max(30).optional(),
  vanLocationName: z.string().max(100).optional(),
  amount: z.number().optional(), // Client-submitted total for cross-verification
});

export async function POST(req: NextRequest) {
  try {
    // 1. Rate Limiting (20 order creations per 60 seconds per IP, sensitive in production)
    const clientIp = getClientIp(req);
    const rateLimit = await checkRateLimit(clientIp, "create-payment-order", 20, 60, {
      sensitive: true,
    });
    if (!rateLimit.success) {
      if (rateLimit.error === "RATE_LIMITER_UNAVAILABLE") {
        return NextResponse.json(
          { error: "Payment order service temporarily unavailable. Please retry shortly." },
          { status: 503 }
        );
      }
      return NextResponse.json(
        { error: "Too many payment order attempts. Please slow down." },
        { status: 429 }
      );
    }

    // 2. Safe JSON Parse
    let rawBody: unknown;
    try {
      rawBody = await req.json();
    } catch {
      return NextResponse.json({ error: "Malformed JSON payload" }, { status: 400 });
    }

    // 3. Zod Input Validation
    const parsed = CreateOrderInputSchema.safeParse(rawBody);
    if (!parsed.success) {
      const errorMsg = parsed.error.issues
        .map((iss) => `${iss.path.join(".") || "field"}: ${iss.message}`)
        .join("; ");
      return NextResponse.json(
        { error: `Validation Error: ${errorMsg}` },
        { status: 400 }
      );
    }

    const {
      items,
      promoCode,
      isMember,
      currency,
      receipt,
      customerName,
      customerPhone,
      vanLocationName,
      amount: clientSubmittedAmount,
    } = parsed.data;

    // 4. Server-Side Menu Validation & Price Recomputation
    let subtotal = 0;
    const validatedItems: StoredPaymentItem[] = [];
    let serverCalculatedTotal = 0;
    let memberDiscount = 0;
    let promoDiscount = 0;
    let deliveryFee = 0;
    let estimatedTax = 0;
    let promoType: string | null = null;

    if (items && items.length > 0) {
      for (const item of items) {
        const menuItem = MENU_MAP.get(item.id);
        if (!menuItem) {
          return NextResponse.json(
            { error: `Unknown product ID: '${item.id}'. Product not found in authoritative menu catalog.` },
            { status: 400 }
          );
        }
        const itemSubtotal = menuItem.price * item.quantity;
        subtotal += itemSubtotal;
        validatedItems.push({
          id: menuItem.id,
          name: menuItem.name,
          price: menuItem.price,
          quantity: item.quantity,
        });
      }

      // 5. Server-Side Discount & Promo Code Evaluation
      if (isMember) {
        memberDiscount = Math.round(subtotal * 0.1);
      }

      if (promoCode) {
        const normalizedCode = promoCode.trim().toUpperCase();
        if (normalizedCode === "BREW10" || normalizedCode === "WELCOME") {
          promoDiscount = Math.round(subtotal * 0.1);
          promoType = "10_PERCENT_OFF";
        } else if (normalizedCode.startsWith("BREWCARE")) {
          // Recovery credit generated by Agent 6 Guest Care or campaign vouchers
          promoDiscount = Math.min(subtotal, 50);
          promoType = "GUEST_RECOVERY_50";
        } else if (normalizedCode === "FREEDEL") {
          promoDiscount = 0;
          promoType = "FREE_DELIVERY";
        } else {
          return NextResponse.json(
            { error: `Invalid or unrecognized promo code: '${promoCode}'. Available codes: BREW10, WELCOME, or valid BREWCARE recovery vouchers.` },
            { status: 400 }
          );
        }
      }

      // 6. Server-Side Delivery & Tax Calculations
      const isDeliveryFree =
        Boolean(isMember) || subtotal >= 399 || promoType === "FREE_DELIVERY" || promoDiscount > 0;
      deliveryFee = validatedItems.length === 0 ? 0 : isDeliveryFree ? 0 : 49;

      const taxableAmount = Math.max(0, subtotal - memberDiscount - promoDiscount);
      estimatedTax = validatedItems.length === 0 ? 0 : Math.round(taxableAmount * 0.05); // 5% GST
      serverCalculatedTotal = Math.max(0, taxableAmount + estimatedTax + deliveryFee);

      // 7. Anti-Tampering Check: If client passed an amount, it MUST match the server calculation
      if (clientSubmittedAmount !== undefined && Math.abs(clientSubmittedAmount - serverCalculatedTotal) > 1) {
        return NextResponse.json(
          {
            error: `Price tampering detected: client submitted amount (₹${clientSubmittedAmount}) does not match server-calculated total (₹${serverCalculatedTotal}).`,
            serverCalculatedTotal,
          },
          { status: 400 }
        );
      }
    } else {
      // Legacy fallback or direct amount check
      if (clientSubmittedAmount === undefined || clientSubmittedAmount <= 0) {
        return NextResponse.json(
          { error: "Invalid payment request: either 'items' list or a positive 'amount' is required." },
          { status: 400 }
        );
      }
      serverCalculatedTotal = clientSubmittedAmount;
      subtotal = clientSubmittedAmount;
    }

    const amountInPaise = Math.round(serverCalculatedTotal * 100);
    const effectiveReceipt = receipt || `rcpt_${Date.now()}`;
    const sanitizedName = customerName || "Sanctuary Guest";
    const maskedPhone = customerPhone ? maskPhone(customerPhone) : "N/A";

    const internalOrderId = `ord_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;

    // 8. Create Persistent Pending Order Record in Cloud Firestore
    const pendingOrder: StoredPaymentOrder = {
      orderId: internalOrderId,
      customerReference: sanitizedName,
      customerName: sanitizedName,
      customerPhone: customerPhone || undefined,
      items: validatedItems,
      subtotal,
      discountAmount: memberDiscount + promoDiscount,
      appliedPromotion: promoType || undefined,
      taxAmount: estimatedTax,
      deliveryFee,
      finalTotal: serverCalculatedTotal,
      amountInPaise,
      currency,
      receipt: effectiveReceipt,
      paymentStatus: "pending",
      orderStatus: "pending",
      createdAt: Date.now(),
      updatedAt: Date.now(),
      vanLocationName: vanLocationName || "BREW Mobile Station",
    };
    await saveStoredPaymentOrder(pendingOrder);

    const keyId = process.env.RAZORPAY_KEY_ID || process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID;
    const keySecret = process.env.RAZORPAY_KEY_SECRET;

    let finalOrderId = "";
    let isLiveGateway = false;

    // 9. If Razorpay API credentials are configured, request live order from Razorpay
    if (keyId && keySecret) {
      try {
        const authHeader = "Basic " + Buffer.from(`${keyId}:${keySecret}`).toString("base64");
        const rzpRes = await fetch("https://api.razorpay.com/v1/orders", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: authHeader,
          },
          body: JSON.stringify({
            amount: amountInPaise,
            currency,
            receipt: effectiveReceipt,
            payment_capture: 1,
            notes: {
              internalOrderId,
              customerName: sanitizedName,
              customerPhone: maskedPhone,
              vanLocation: vanLocationName || "BREW Mobile Station",
              itemCount: validatedItems.length,
            },
          }),
        });

        if (!rzpRes.ok) {
          const errorData = await rzpRes.json();
          console.error("Razorpay order creation failed:", errorData);
          // Safely update pending internal order to failed
          pendingOrder.paymentStatus = "failed";
          pendingOrder.updatedAt = Date.now();
          await saveStoredPaymentOrder(pendingOrder);

          return NextResponse.json(
            { error: errorData.error?.description || "Failed to create Razorpay order" },
            { status: rzpRes.status }
          );
        }

        const rzpOrder = await rzpRes.json();
        finalOrderId = rzpOrder.id;
        isLiveGateway = true;
      } catch (rzpErr) {
        // Network/gateway exception
        pendingOrder.paymentStatus = "failed";
        pendingOrder.updatedAt = Date.now();
        await saveStoredPaymentOrder(pendingOrder);
        throw rzpErr;
      }
    } else {
      // Test / Simulation Gateway
      finalOrderId = `order_test_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
    }

    // 10. Persist Razorpay Order ID to the Durable Order Record
    pendingOrder.razorpayOrderId = finalOrderId;
    pendingOrder.updatedAt = Date.now();
    await saveStoredPaymentOrder(pendingOrder);

    return NextResponse.json({
      success: true,
      orderId: finalOrderId,
      internalOrderId,
      amount: amountInPaise,
      currency,
      keyId: keyId || "rzp_test_brew_mobile_2026",
      isLive: isLiveGateway,
      breakdown: {
        subtotal,
        memberDiscount,
        promoDiscount,
        deliveryFee,
        tax: estimatedTax,
        finalTotal: serverCalculatedTotal,
      },
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : "Internal payment error";
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
